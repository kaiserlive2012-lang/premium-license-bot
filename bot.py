@routes.post('/api/verify')
async def api_verify(request):
    try:
        data = await request.json()
    except Exception:
        return web.json_response({"success": False, "message": "Invalid JSON body"}, status=400)

    key_input = (data.get("key") or "").strip().upper()
    hwid_input = (data.get("hwid") or "").strip()

    if not key_input:
        return web.json_response({"success": False, "message": "License key is required."}, status=400)
    if not hwid_input:
        return web.json_response({"success": False, "message": "Hardware ID is required."}, status=400)

    with get_db() as conn:
        cur = conn.execute("SELECT * FROM licenses WHERE key_code = ?", (key_input,))
        row = cur.fetchone()

        if not row:
            return web.json_response({"success": False, "message": "Invalid license key!"})

        if not row["is_active"]:
            return web.json_response({"success": False, "message": "This license key has been revoked by admin."})

        # Check HWID Binding
        db_hwid = row["hwid"]
        now = datetime.utcnow()

        if not db_hwid:
            # First activation: bind HWID and compute expiry
            activated_at_str = now.isoformat()
            duration = row["duration_days"]
            if duration > 0:
                expires_dt = now + timedelta(days=duration)
                expires_str = expires_dt.isoformat()
            else:
                expires_str = None  # Lifetime

            conn.execute("""
                UPDATE licenses 
                SET hwid = ?, activated_at = ?, expires_at = ?
                WHERE key_code = ?
            """, (hwid_input, activated_at_str, expires_str, key_input))
            conn.commit()
            
            days_left = duration if duration > 0 else 99999
            return web.json_response({
                "success": true,
                "message": "License activated successfully!",
                "key": key_input,
                "expires": expires_str or "Lifetime",
                "days_left": days_left,
                "version": APP_VERSION,
                "developed_by": APP_DEVELOPER
            })

        # Existing activation: verify HWID
        if db_hwid != hwid_input:
            return web.json_response({
                "success": False,
                "message": "HWID mismatch! This key is locked to another computer. Ask your admin to reset HWID."
            })

        # Check expiration
        expires_str = row["expires_at"]
        if expires_str:
            try:
                exp_dt = datetime.fromisoformat(expires_str)
                if now > exp_dt:
                    return web.json_response({
                        "success": False,
                        "message": f"License expired on {exp_dt.strftime('%Y-%m-%d %H:%M:%S')} UTC!"
                    })
                days_left = max(0, (exp_dt - now).days)
            except Exception:
                days_left = 30
        else:
            days_left = 99999

        return web.json_response({
            "success": True,
            "message": "License active and valid.",
            "key": key_input,
            "expires": expires_str or "Lifetime",
            "days_left": days_left,
            "version": APP_VERSION,
            "developed_by": APP_DEVELOPER
        })

